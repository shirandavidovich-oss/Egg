"""Writes art/physics/elec-data.js (the compact content the game ships) from
art/source/elec/content/worlds_and_scenes.json. Ids get an "E" prefix (EW01-S01) so they never
clash with the mechanics worlds. Run: python3 art/source/elec/build_elec_data.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'content', 'worlds_and_scenes.json')))
E = lambda i: 'E' + i
out = {
  'worlds': [{'id': E(w['id']), 'title': w['title'], 'subtitle': w['subtitle'], 'track': w['track'], 'sceneIds': [E(x) for x in w['sceneIds']]} for w in d['worlds']],
  'scenes': [{'id': E(s['id']), 'w': E(s['worldId']), 'title': s['title'], 'family': s['family'], 'story': s['story'], 'objective': s['goal'],
              'difficulty': s['difficulty'], 'params': s['params'], 'skills': s['skills'],
              'packPrompts': [m['prompt'] for m in s['missions']]} for s in d['scenes']],
  'models': {k: {'label': m['label'], 'knobs': m['knobs'], 'readouts': {r: v[0] for r, v in m['readouts'].items()}} for k, m in d['modelFamilies'].items()},
}
js = ("// generated by art/source/elec/build_elec_data.py from worlds_and_scenes.json (do not edit by hand)\n"
      "const ELEC_DATA = " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n"
      'if (typeof module !== "undefined") module.exports = ELEC_DATA;\n')
open(os.path.join(here, '..', '..', 'physics', 'elec-data.js'), 'w').write(js)
print(len(js) // 1024, 'KB')
