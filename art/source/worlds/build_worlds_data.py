"""Writes art/physics/worlds-data.js (the compact content the game ships) from
art/source/worlds/content/worlds_and_scenes.json. Run: python3 art/source/worlds/build_worlds_data.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'content', 'worlds_and_scenes.json')))
out = {
  'worlds': [{k: w[k] for k in ('id', 'title', 'subtitle', 'track', 'sceneIds')} for w in d['worlds']],
  'scenes': [{'id': s['id'], 'w': s['worldId'], 'title': s['title'], 'family': s['family'], 'story': s['story'],
              'objective': s['objective'], 'difficulty': s['difficulty'], 'params': s['params'], 'skills': s['skills']} for s in d['scenes']],
  'models': {k: {'label': m['label'], 'knobs': m['knobs'], 'readouts': m['readouts']} for k, m in d['models'].items()},
}
js = ("// generated by art/source/worlds/build_worlds_data.py from worlds_and_scenes.json (do not edit by hand)\n"
      "const WORLDS_DATA = " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n"
      'if (typeof module !== "undefined") module.exports = WORLDS_DATA;\n')
open(os.path.join(here, '..', '..', 'physics', 'worlds-data.js'), 'w').write(js)
print(len(js) // 1024, 'KB')
